import assert from "node:assert/strict";
import { readdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../skills/", import.meta.url);
const output = new URL("../src/generated-skills.js", import.meta.url);
const files = {};
const compare = (a, b) => a.name.localeCompare(b.name);

/** Workers cannot read plugin files at runtime. Package every text reference in the MCP resources. */
async function includeSkill(name) {
  const skillRoot = new URL(name + "/", root);
  const skillFile = await readFile(new URL("SKILL.md", skillRoot), "utf8");
  assert.match(skillFile, new RegExp("^---\\nname: " + name + "\\n"), "Skill name must match directory");
  assert.match(skillFile, /^---\n[\s\S]*?\ndescription: .+/m, "Skill must have a description");

  async function collect(directory, relative = "", depth = 0) {
    assert.ok(depth <= 4, "Skill references may not be nested more than four levels");
    const entries = (await readdir(directory, { withFileTypes: true })).sort(compare);
    for (const entry of entries) {
      assert.ok(!entry.name.startsWith(".") && entry.name !== "node_modules", "Hidden or dependency files are not skill resources");
      const path = relative + entry.name;
      if (entry.isDirectory()) {
        await collect(new URL(entry.name + "/", directory), path + "/", depth + 1);
      } else {
        assert.ok(entry.isFile() && /\.(md|json|txt|js|ts|yaml|yml)$/.test(entry.name),
          "Only UTF-8 text resources are supported in MCP skills: " + path);
        const contents = await readFile(new URL(entry.name, directory), "utf8");
        assert.ok(Buffer.byteLength(contents, "utf8") <= 128 * 1024, "Skill resource is too large: " + path);
        files[name + "/" + path] = contents;
      }
    }
  }
  await collect(skillRoot);
}

for (const entry of (await readdir(root, { withFileTypes: true })).sort(compare)) {
  assert.ok(entry.isDirectory(), "All entries under skills/ must be skill directories");
  await includeSkill(entry.name);
}
assert.ok(Object.keys(files).length > 0, "No skills found");

const generated = "// Generated by scripts/generate-skills.mjs. Do not edit manually.\n" +
  "export const skillFiles = " + JSON.stringify(files, null, 2) + ";\n";
if (process.argv.includes("--check")) {
  assert.equal(await readFile(output, "utf8"), generated,
    "Skills bundle is stale; run npm run generate:skills");
} else {
  await writeFile(output, generated);
}
